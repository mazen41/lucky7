    public function translateDataKeys($data) {
        if (empty($data)) return []; 
        $translatedData = [];
        foreach ($data as $row) {
            $translatedRow = [];
            foreach ($row as $key => $value) {
                // Map DB alias to Arabic Header, or use original key if not found
                $translatedKey = $this->columnTranslations[$key] ?? $key;
                $translatedRow[$translatedKey] = $value;
            } 
            $translatedData[] = $translatedRow;
        } 
        return $translatedData;
    }

    public function exportToCSV($data, $filename) {
        if (empty($data)) return;
        header('Content-Type: text/csv; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '.csv"');
        $output = fopen('php://output', 'w');
        fprintf($output, chr(0xEF) . chr(0xBB) . chr(0xBF)); // BOM for Excel Arabic support
        fputcsv($output, array_keys($data[0]));
        foreach ($data as $row) { fputcsv($output, $row); }
        fclose($output); 
        exit;
    }

    public function exportToPDF($data, $summary, $report_title, $filename) {
        // --- INITIALIZE PDF ---
        $pdf = new ModernReportPDF('P', PDF_UNIT, 'A4', true, 'UTF-8', false);
        $pdf->setReportTitle($report_title);
        
        // --- METADATA & SETTINGS ---
        $pdf->setRTL(true);
        $pdf->SetCreator('Mai Salon System');
        $pdf->SetAuthor('Admin');
        $pdf->SetTitle($report_title);
        $pdf->SetMargins(15, 35, 15);
        $pdf->SetHeaderMargin(15);
        $pdf->SetFooterMargin(15);
        $pdf->SetAutoPageBreak(TRUE, 25);
        
        // --- SET FONT ---
        $pdf->SetFont('notosansarabic', '', 10);
        $pdf->AddPage();

        // --- MODERN HTML & CSS DESIGN ---
        $textColor    = '#343a40';
        $headingColor = '#212529';
        $borderColor  = '#dee2e6';
        $lightBg      = '#f8f9fa';

        $html = <<<EOF
<style>
    body { font-family: "notosansarabic", sans-serif; color: {$textColor}; line-height: 1.6; direction: rtl; }
    h3 { font-size: 14pt; color: {$headingColor}; border-bottom: 2px solid {$borderColor}; padding-bottom: 10px; margin-top: 20px; margin-bottom: 15px; }
