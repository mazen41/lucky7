    .summary-card .value { font-size: 14pt; color: {$headingColor}; font-weight: bold; display: block; margin-top: 5px; }
    .data-table { width: 100%; border-collapse: collapse; margin-top: 15px; }
    .data-table th { background-color: #343a40; color: #ffffff; font-weight: bold; padding: 10px; border: 1px solid #454d55; font-size: 10pt; text-align: center; }
    .data-table td { border: 1px solid {$borderColor}; padding: 9px; font-size: 9pt; text-align: center; }
    .row-odd { background-color: {$lightBg}; }
    .no-data { text-align:center; padding: 25px; color: #7f8c8d; background-color: {$lightBg}; border: 1px dashed #ccc; }
</style>
EOF;

        // --- SUMMARY SECTION ---
        if (!empty($summary)) {
            $html .= '<h3>ملخص التقرير</h3>';
            $html .= '<table width="100%" cellspacing="5" cellpadding="0"><tr>';
            $count = 0; $itemsInRow = 3;
            foreach ($summary as $key => $value) {
                if ($count > 0 && $count % $itemsInRow == 0) { $html .= '</tr><tr>'; }
                $html .= '<td width="' . (100 / $itemsInRow) . '%"><div class="summary-card"><span class="label">' . htmlspecialchars($key) . '</span><br/><span class="value">' . htmlspecialchars($value) . '</span></div></td>';
                $count++;
            }
            while ($count % $itemsInRow != 0) { $html .= '<td></td>'; $count++; }
            $html .= '</tr></table>';
        }

        // --- DETAILED DATA SECTION ---
        $html .= '<h3>البيانات التفصيلية</h3>';
        if (!empty($data)) {
            $html .= '<table class="data-table" nobr="true"><thead><tr>';
            foreach (array_keys($data[0]) as $header) { $html .= '<th>' . htmlspecialchars($header) . '</th>'; }
            $html .= '</tr></thead><tbody>';
            $i = 0;
            foreach ($data as $row) {
                $rowClass = ($i++ % 2 != 0) ? 'row-odd' : '';
                $html .= '<tr class="' . $rowClass . '">';
                foreach ($row as $cell) { $html .= '<td>' . htmlspecialchars($cell ?? '-') . '</td>'; }
                $html .= '</tr>';
            }
            $html .= '</tbody></table>';
        } else {
             $html .= '<div class="no-data">لا توجد بيانات متاحة لهذا التقرير.</div>';
        }

        $pdf->writeHTML($html, true, false, true, false, '');
        if (ob_get_length()) { @ob_end_clean(); }

        $cleanFilename = preg_replace('/[^A-Za-z0-9\-_]/', '', $filename);
        $pdf->Output($cleanFilename . '.pdf', 'D');
        exit;
    }
