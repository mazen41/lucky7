    public function getHRReport($filters = []) {
        // Calculated from invoice_items to allow dynamic date filtering
        $where_conditions = ["i.status = 'paid'", "i.is_return = 0", "ii.item_type = 'service'"];
        $params = [];

        if (!empty($filters['date_from'])) {
            $where_conditions[] = "DATE(i.created_at) >= ?";
            $params[] = $filters['date_from'];
        }
        if (!empty($filters['date_to'])) {
            $where_conditions[] = "DATE(i.created_at) <= ?";
            $params[] = $filters['date_to'];
        }
        if (!empty($filters['specialist_id'])) {
            $where_conditions[] = "ii.specialist_id = ?";
            $params[] = $filters['specialist_id'];
        }

        $query = "SELECT 
                    COALESCE(ii.specialist_name, 'Unknown') as specialist_name,
                    COUNT(ii.id) as services_performed,
                    SUM(ii.total_price) as total_revenue
                  FROM invoice_items ii
                  JOIN invoices i ON ii.invoice_id = i.id
                  WHERE " . implode(' AND ', $where_conditions) . "
                  GROUP BY ii.specialist_name
                  ORDER BY total_revenue DESC";

        $stmt = $this->db->prepare($query);
        $stmt->execute($params);
        $data = $stmt->fetchAll(PDO::FETCH_ASSOC);

        return [
            'data' => $data, 
            'summary' => [
                'إجمالي إيراد الخدمات' => number_format(array_sum(array_column($data, 'total_revenue')), 2) . ' ر.س'
            ]
        ];
    }

