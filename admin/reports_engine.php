    // 8. CUSTOMERS REPORT
    // ==========================================
    public function getCustomersReport($filters = []) {
        $query = "
            SELECT
                c.id as customer_code,
                COALESCE(c.name_ar, c.name, 'N/A') as customer_name,
                c.phone,
                COALESCE(inv_stats.total_spent, 0) as total_spent,
                COALESCE(inv_stats.visit_count, 0) as visit_count,
                DATE_FORMAT(inv_stats.last_visit, '%Y-%m-%d') as last_visit
            FROM customers c
            LEFT JOIN (
                SELECT
                    customer_id,
                    SUM(total_amount) as total_spent,
                    COUNT(id) as visit_count,
                    MAX(created_at) as last_visit
                FROM invoices
                WHERE status = 'paid' AND customer_id IS NOT NULL AND is_return = 0
                GROUP BY customer_id
            ) AS inv_stats ON c.id = inv_stats.customer_id
            ORDER BY total_spent DESC"; // Top spenders first
        $stmt = $this->db->query($query); $customers = $stmt->fetchAll(PDO::FETCH_ASSOC);
        return ['data' => $customers, 'summary' => ['إجمالي العملاء المسجلين' => count($customers)]];
    }

