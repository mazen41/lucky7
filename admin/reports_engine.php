    public function getUserAttendanceReport($filters = []) {
        // Since no specific attendance table was provided, we act like shifts are attendance records
        // This is common in simple POS systems
        $where_conditions = ["s.closed_at IS NOT NULL"];
        $params = [];

        if (!empty($filters['date_from'])) {
            $where_conditions[] = "DATE(s.opened_at) >= ?";
            $params[] = $filters['date_from'];
        }
        if (!empty($filters['date_to'])) {
            $where_conditions[] = "DATE(s.opened_at) <= ?";
            $params[] = $filters['date_to'];
        }
        if (!empty($filters['user_id'])) {
            $where_conditions[] = "s.user_id = ?";
            $params[] = $filters['user_id'];
        }

        $query = "SELECT 
                    u.name as user_name,
                    DATE_FORMAT(s.opened_at, '%Y-%m-%d') as attendance_date,
                    DATE_FORMAT(s.opened_at, '%H:%i') as check_in_time,
                    DATE_FORMAT(s.closed_at, '%H:%i') as check_out_time,
                    ROUND(TIMESTAMPDIFF(MINUTE, s.opened_at, s.closed_at) / 60, 2) as hours_worked
                  FROM shifts s
                  LEFT JOIN users u ON s.user_id = u.id
                  WHERE " . implode(' AND ', $where_conditions) . "
                  ORDER BY s.opened_at DESC";

        $stmt = $this->db->prepare($query);
        $stmt->execute($params);
        $data = $stmt->fetchAll(PDO::FETCH_ASSOC);

        $total_hours = array_sum(array_column($data, 'hours_worked'));

        return [
            'data' => $data, 
            'summary' => [
                'إجمالي ساعات العمل' => number_format($total_hours, 2) . ' ساعة'
            ]
        ];
    }

