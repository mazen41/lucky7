    // 3. NET PROFIT REPORT
    // ==========================================
    public function getNetProfitReport($filters = []) {
        $params = []; $date_from = $filters['date_from'] ?? null; $date_to = $filters['date_to'] ?? null;
        
        // Sales
        $sales_q = "SELECT SUM(total_amount) FROM invoices WHERE status = 'paid' AND is_return = 0";
        if($date_from) { $sales_q .= " AND DATE(created_at) >= ?"; $params[] = $date_from; }
        if($date_to) { $sales_q .= " AND DATE(created_at) <= ?"; $params[] = $date_to; }
        $stmt_sales = $this->db->prepare($sales_q); $stmt_sales->execute($params); $total_sales = $stmt_sales->fetchColumn() ?: 0;
        
        // Returns
        $returns_q = "SELECT SUM(ABS(total_amount)) FROM invoices WHERE is_return = 1"; // ABS because returns are stored as negative
        $params_ret = [];
        if($date_from) { $returns_q .= " AND DATE(created_at) >= ?"; $params_ret[] = $date_from; }
        if($date_to) { $returns_q .= " AND DATE(created_at) <= ?"; $params_ret[] = $date_to; }
        $stmt_returns = $this->db->prepare($returns_q); $stmt_returns->execute($params_ret);
        $total_returns = $stmt_returns->fetchColumn() ?: 0;
        
        // Expenses
        $params_exp = []; $expenses_q = "SELECT SUM(amount) FROM expenses WHERE 1=1";
        if($date_from) { $expenses_q .= " AND expense_date >= ?"; $params_exp[] = $date_from; }
        if($date_to) { $expenses_q .= " AND expense_date <= ?"; $params_exp[] = $date_to; }
        $stmt_expenses = $this->db->prepare($expenses_q); $stmt_expenses->execute($params_exp); $total_expenses = $stmt_expenses->fetchColumn() ?: 0;
        
        $data = [
            ['title' => 'إجمالي المبيعات', 'value' => number_format($total_sales, 2) . ' ر.س'],
            ['title' => 'إجمالي المرتجعات', 'value' => number_format($total_returns, 2) . ' ر.س'],
            ['title' => 'إجمالي المصروفات', 'value' => number_format($total_expenses, 2) . ' ر.س'],
        ];
        
        $net_profit = $total_sales - $total_returns - $total_expenses;
        
        $summary = ['الربح الصافي' => number_format($net_profit, 2) . ' ر.س'];
        return ['data' => $data, 'summary' => $summary];
    }

