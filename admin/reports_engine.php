    // ==========================================
    // NEW: 3. TRIAL BALANCE REPORT
    // ==========================================
    public function getTrialBalanceReport($filters = []) {
        $date_from = $filters['date_from'] ?? date('Y-m-01');
        $date_to = $filters['date_to'] ?? date('Y-m-t');

        $reportData = $this->accountingModel->getTrialBalanceData($date_from, $date_to);
        
        $grand_total_debit = 0;
        $grand_total_credit = 0;

        foreach ($reportData as &$row) { // Use reference to modify array directly
             $total_debit = (float)$row['total_debit'];
             $total_credit = (float)$row['total_credit'];
             $grand_total_debit += $total_debit;
             $grand_total_credit += $total_credit;

             $balance_val = ($row['normal_balance'] === 'debit') ? $total_debit - $total_credit : $total_credit - $total_debit;
             
             $row['balance'] = number_format(abs($balance_val), 2);
             $row['balance_type'] = $balance_val >= 0 ? ($row['normal_balance'] === 'debit' ? 'مدين' : 'دائن') : 'عكسي';
             
             // Format numbers
             $row['total_debit'] = number_format($total_debit, 2);
             $row['total_credit'] = number_format($total_credit, 2);
             
             // Unset original values to clean up output
             unset($row['normal_balance']);
        }
        
        $is_balanced = abs($grand_total_debit - $grand_total_credit) < 0.01;

        $summary = [
            'إجمالي المدين' => number_format($grand_total_debit, 2) . ' ر.س',
            'إجمالي الدائن' => number_format($grand_total_credit, 2) . ' ر.س',
            'الحالة' => $is_balanced ? 'متوازن' : 'غير متوازن',
        ];

        return ['data' => $reportData, 'summary' => $summary];
    }
    
