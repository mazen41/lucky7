    // NEW: SALES BY ITEM REPORT
    // ==========================================
    public function getSalesByItemReport($filters = []) {
        $where_conditions = ["i.status = 'paid'", "i.is_return = 0"];
        $params = [];

        if (!empty($filters['date_from'])) {
            $where_conditions[] = "DATE(i.created_at) >= ?";
            $params[] = $filters['date_from'];
        }
        if (!empty($filters['date_to'])) {
            $where_conditions[] = "DATE(i.created_at) <= ?";
            $params[] = $filters['date_to'];
        }

        $query = "
            SELECT
                ii.item_name,
                CASE ii.item_type
                    WHEN 'service' THEN 'خدمة'
                    WHEN 'product' THEN 'منتج'
                    ELSE ii.item_type
                END as item_type,
                SUM(ii.quantity) as total_quantity_sold,
                COUNT(DISTINCT ii.invoice_id) as invoice_count,
                SUM(ii.total_price) as total_revenue
            FROM invoice_items ii
            JOIN invoices i ON ii.invoice_id = i.id
            WHERE " . implode(' AND ', $where_conditions) . "
            GROUP BY ii.item_id, ii.item_type, ii.item_name
            ORDER BY total_revenue DESC";

        $stmt = $this->db->prepare($query);
        $stmt->execute($params);
        $data = $stmt->fetchAll(PDO::FETCH_ASSOC);

        $total_revenue = array_sum(array_column($data, 'total_revenue'));
        $total_quantity = array_sum(array_column($data, 'total_quantity_sold'));
        
        return [
            'data' => $data,
            'summary' => [
                'إجمالي الإيرادات من الأصناف' => number_format($total_revenue, 2) . ' ر.س',
                'إجمالي عدد القطع المباعة' => number_format($total_quantity),
                'عدد الأصناف الفريدة المباعة' => count($data)
            ]
        ];
    }

