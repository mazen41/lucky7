<?php
// Prevent browser caching and setup error reporting
ini_set('display_errors', 1);
error_reporting(E_ALL);

require_once 'auth.php';
require_once '../config/database.php';
require_once __DIR__ . '/../vendor/autoload.php';

use TCPDF;

checkAdminAuth();
$database = new Database();
$db = $database->getConnection();

// Validate form ID from GET
$client_form_id = filter_input(INPUT_GET, 'id', FILTER_VALIDATE_INT);
if (!$client_form_id) {
    die("Invalid Form ID provided.");
}

// Fetch submission data
try {
    $stmt = $db->prepare("
        SELECT
            cf.answers,
            cf.created_at,
            c.name_ar AS customer_name,
            hf.name AS form_name
        FROM client_forms cf
        JOIN customers c ON cf.customer_id = c.id
        JOIN health_forms hf ON cf.form_id = hf.id
        WHERE cf.id = ?
    ");
    $stmt->execute([$client_form_id]);
    $submission = $stmt->fetch(PDO::FETCH_ASSOC);
} catch (PDOException $e) {
    error_log("DB error fetching submission: " . $e->getMessage());
    die("Database error while fetching submission.");
}

if (!$submission) {
    die("Could not find the requested form submission.");
}

// Fetch questions map (id => question_text)
try {
    $all_questions_stmt = $db->query("SELECT id, question_text FROM health_form_questions");
    $questions_map = $all_questions_stmt->fetchAll(PDO::FETCH_KEY_PAIR);
} catch (PDOException $e) {
    error_log("DB error fetching questions: " . $e->getMessage());
    $questions_map = [];
}

// Decode answers JSON safely
$answers = json_decode($submission['answers'], true);
if (!is_array($answers)) {
    $answers = [];
}

/**
 * Custom PDF class for a branded footer
 */
class CustomPDF extends TCPDF {
    public function Header() {}
    
    public function Footer() {
        $this->SetY(-15);
        // Use our new custom font in the footer
        $this->SetFont('notosansarabic', 'I', 8);
        $this->SetTextColor(150, 150, 150);
        $this->Cell(0, 5, 'Generated by Mai Salon System', 0, false, 'C');
        $this->Ln(4);
        $this->Cell(0, 5, 'Page ' . $this->getAliasNumPage() . ' of ' . $this->getAliasNbPages(), 0, false, 'C');
    }
}

// Initialize PDF
$pdf = new CustomPDF(PDF_PAGE_ORIENTATION, PDF_UNIT, PDF_PAGE_FORMAT, true, 'UTF-8', false);

// 1. Set RTL for Arabic
$pdf->setRTL(true);

// 2. Document metadata
$pdf->SetCreator('Mai Salon System');
$pdf->SetAuthor(htmlspecialchars($submission['customer_name']));
$pdf->SetTitle(htmlspecialchars($submission['form_name']) . ' - ' . htmlspecialchars($submission['customer_name']));

// 3. Margins
$pdf->SetMargins(15, 15, 15);
$pdf->SetHeaderMargin(0);
$pdf->SetFooterMargin(15);
$pdf->SetAutoPageBreak(TRUE, 25);

// 4. *** IMPORTANT: Set the default font to our new ARABIC font ***
$pdf->SetFont('notosansarabic', '', 10);

// Add page
$pdf->AddPage();

// ---------------------------------------------------------
// MODERN HTML & CSS DESIGN
// ---------------------------------------------------------

$textColor   = '#343a40';
$headingColor= '#212529';
$borderColor = '#dee2e6';
$lightBg     = '#f8f9fa';

$formattedDate = date('F j, Y, g:i a', strtotime($submission['created_at']));

$logoPath = 'path/to/your/logo.png'; // Make sure this path is correct
$logoHtml = file_exists($logoPath)
    ? '<img src="' . $logoPath . '" width="150" style="width:150px;">'
    : '<h2 style="font-family: notosansarabic; color: ' . $headingColor . ';">Mai Salon</h2>';

// In the CSS, 'notosansarabic' is used as the font-family.
$html = <<<EOF
<style>
    body {
        /* Use our newly added 'notosansarabic' font */
        font-family: "notosansarabic", sans-serif; 
        color: {$textColor};
        line-height: 1.6;
    }
    h1 {
        font-size: 24pt;
        color: {$headingColor};
        margin-bottom: 0;
    }
    h3 {
        font-size: 14pt;
        border-bottom: 2px solid {$borderColor};
        padding-bottom: 10px;
        margin-top: 25px;
    }
    .header-table {
        width: 100%;
        margin-bottom: 30px;
    }
    .header-info {
        text-align: left; /* Visually left in RTL */
    }
    .info-box {
        background-color: {$lightBg};
        border: 1px solid {$borderColor};
        padding: 15px; 
        margin-bottom: 30px;
    }
    .info-box .label {
        font-size: 9pt;
        color: #6c757d;
    }
    .info-box .value {
        font-size: 12pt;
        color: {$headingColor};
    }
    .qa-item {
        margin-bottom: 20px; 
        page-break-inside: avoid;
    }
    .question-text {
        font-size: 11pt;
        color: {$headingColor};
        margin-bottom: 8px;
    }
    .answer-text {
        font-size: 10pt;
        color: {$textColor};
        background-color: #ffffff;
        border: 1px solid {$borderColor};
        padding: 12px;
        text-align: justify;
    }
    .no-answer {
        color: #999;
        font-style: italic;
    }
</style>

<table class="header-table" cellpadding="0" cellspacing="0">
    <tr>
        <td width="50%" style="text-align: right;">{$logoHtml}</td>
        <td width="50%" class="header-info"><h1>{$submission['form_name']}</h1></td>
    </tr>
</table>

<div class="info-box">
    <table width="100%">
        <tr>
            <td width="50%">
                <span class="label">اسم العميل</span><br/>
                <span class="value">{$submission['customer_name']}</span>
            </td>
            <td width="50%">
                <span class="label">تاريخ التقديم</span><br/>
                <span class="value">{$formattedDate}</span>
            </td>
        </tr>
    </table>
</div>

<h3>الإجابات المقدمة</h3>
<br/>
EOF;

if (!empty($answers)) {
    foreach ($answers as $questionId => $answerText) {
        $questionText = isset($questions_map[$questionId]) 
            ? htmlspecialchars($questions_map[$questionId]) 
            : 'سؤال غير معروف';
        
        $cleanAnswer = is_array($answerText) 
            ? htmlspecialchars(implode(', ', $answerText)) 
            : htmlspecialchars((string)$answerText);

        $displayAnswer = $cleanAnswer === '' 
            ? '<span class="no-answer">(لم يتم تقديم إجابة)</span>' 
            : nl2br($cleanAnswer);

        $html .= <<<HTML
        <div class="qa-item">
            <div class="question-text">{$questionText}</div>
            <div class="answer-text">{$displayAnswer}</div>
        </div>
HTML;
    }
} else {
    $html .= '<div style="text-align:center; padding:20px; color:#7f8c8d; border: 1px dashed #ccc;">لم يتم تسجيل أي إجابات في هذا النموذج.</div>';
}

$pdf->writeHTML($html, true, false, true, false, '');

if (ob_get_length()) {
    @ob_end_clean();
}

$cleanName = preg_replace('/[^A-Za-z0-9\-_\x{0600}-\x{06FF} ]/u', '', $submission['customer_name']);
$filename = 'Form_' . $client_form_id . '_' . ($cleanName ?: 'Client') . '.pdf';

$pdf->Output($filename, 'D');
exit;
?>